formatter = textwrap.TextWrapper()
def fmt(text, indent1=None, indent2=None, width=None):
    """
    Format text for output to screen and/or log file.
    Individual lines are wrapped with indent.
    """
    if not width:
        try: width = get_terminal_size().columns
        except Exception: width = 79
    if indent1 is None:
        indent1 = ""
        if indent2 is None:
            indent2 = "   "
    elif indent2 is None:
        indent2 = indent1 +"   "
    formatter.width = width
    lines = text.splitlines()
    wlines = []
    for line in lines:
        lineIndent = " " * (len(line) -len(line.lstrip()))
        formatter.initial_indent = indent1
        formatter.subsequent_indent = indent2 +lineIndent
        wlines.append("\n".join(formatter.wrap(line)))
    text = "\n".join(wlines)
    return text

class MessageQueue(list):
    def __init__(self, *args, **kwargs):
        speechQueue = False
        if "speechQueue" in kwargs:
            speechQueue = kwargs["speechQueue"]
            del kwargs["speechQueue"]
        self.speechQueue = speechQueue
        list.__init__(self, *args, **kwargs)
        if speechQueue:
            self.thr = threading.Timer(0, self.watch)
            self.thr.setDaemon(True)
            self.thr.start()

    def output(self, nmsgs=0):
        """
        Output messages based on nmsgs.
        If nmsgs is positive, output that many messages.
        Otherwise, output all pending messages.
        """
        if nmsgs == 0:
            nmsgs = -1
        while len(self) and nmsgs != 0:
            s = self.pop(0)
            safePrint(s)
            if nmsgs > 0:
                nmsgs -= 1

    def watch(self):
        while True:
            if len(self) > 0:
                say(" ")
                while len(self):
                    m = self.pop(0)
                    say(m)
            time.sleep(2.0)

    def append(self, *args, **kwargs):
        conf = Conf()
        try: nmsgs = int(conf.option("queueMessages"))
        except Exception: nmsgs = 0
        if nmsgs <= 0:
            # In case any are pending for some reason.
            self.output(nmsgs)
        if nmsgs > 0:
            list.append(self, *args, **kwargs)
        else:
            safePrint(*args, **kwargs)

