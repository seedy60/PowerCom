# Thread-safe printing, for all that go through the next function.
printLock = threading.Lock()
def safePrint(*args, **kwargs):
    """Safe print path:
        Locks against thread collisions that would intermingle output.
        Limits to about 12 k per single print call.
        (Inspired by WSL Interop 16k limit)
    """
    try:
        sep = kwargs.get('sep', ' ')
        end = kwargs.get('end', '\n')
        kw1 = kwargs.copy()
        kw1["end"] = ""
        kw1["flush"] = True
        txt = sep.join(map(str, args)) + end
    except:
        txt = ''
    lim = 12288
    if len(txt) > lim:
        # Chunking required.
        with printLock:
            while txt:
                print(txt[:lim], **kw1)
                txt = txt[lim:]
        return
    # No need to split up, so just call as if we never looked.
    with printLock: print(*args, **kwargs)

